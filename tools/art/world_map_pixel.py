def canvas(w, h):
    return np.zeros((h, w, 4), np.uint8)


def to_img(arr):
    return Image.fromarray(arr, "RGBA")


def from_img(img):
    return np.asarray(img.convert("RGBA")).copy()


def put(a, x, y, c):
    if 0 <= y < a.shape[0] and 0 <= x < a.shape[1]:
        a[y, x] = c


def rect(a, x, y, w, h, c):
    H, W = a.shape[:2]
    x0, y0, x1, y1 = max(x, 0), max(y, 0), min(x + w, W), min(y + h, H)
    if x1 > x0 and y1 > y0:
        a[y0:y1, x0:x1] = c


def frame_rect(a, x, y, w, h, c):
    rect(a, x, y, w, 1, c)
    rect(a, x, y + h - 1, w, 1, c)
    rect(a, x, y, 1, h, c)
    rect(a, x + w - 1, y, 1, h, c)


def hline(a, x0, x1, y, c):
    rect(a, min(x0, x1), y, abs(x1 - x0) + 1, 1, c)


def vline(a, x, y0, y1, c):
    rect(a, x, min(y0, y1), 1, abs(y1 - y0) + 1, c)


def line(a, x0, y0, x1, y1, c):
    dx, dy = abs(x1 - x0), -abs(y1 - y0)
    sx, sy = (1 if x0 < x1 else -1), (1 if y0 < y1 else -1)
    err = dx + dy
    while True:
        put(a, x0, y0, c)
        if x0 == x1 and y0 == y1:
            break
        e2 = 2 * err
        if e2 >= dy:
            err += dy
            x0 += sx
        if e2 <= dx:
            err += dx
            y0 += sy


def ellipse_mask(w, h, cx, cy, rx, ry):
    yy, xx = np.mgrid[0:h, 0:w]
    return ((xx + 0.5 - cx) / rx) ** 2 + ((yy + 0.5 - cy) / ry) ** 2 <= 1.0


def fill_mask(a, mask, c):
    a[mask] = c


def blend(a, mask, c, k):
    """Trộn màu c vào vùng mask với tỉ lệ k (chỉ pixel đã có màu)."""
    sel = mask & (a[..., 3] > 0)
    a[sel, :3] = (a[sel, :3] * (1 - k) + np.array(c[:3]) * k).astype(np.uint8)


def outline(a, c=OUTLINE):
    """Viền 1 px quanh vùng có alpha (4 hướng), như viền của tranh gốc."""
    m = a[..., 3] > 0
    grow = m.copy()
    grow[1:] |= m[:-1]
    grow[:-1] |= m[1:]
    grow[:, 1:] |= m[:, :-1]
    grow[:, :-1] |= m[:, 1:]
    edge = grow & ~m
    a[edge] = c
    return a


def paste(a, src, x, y):
    """Dán src (numpy RGBA hoặc PIL) lên a tại (x, y), alpha ghi đè (pixel art)."""
    if isinstance(src, Image.Image):
        src = from_img(src)
    h, w = src.shape[:2]
    H, W = a.shape[:2]
    x0, y0, x1, y1 = max(x, 0), max(y, 0), min(x + w, W), min(y + h, H)
    if x1 <= x0 or y1 <= y0:
        return
    s = src[y0 - y:y1 - y, x0 - x:x1 - x]
    m = s[..., 3] > 0
    a[y0:y1, x0:x1][m] = s[m]


def dither_fill(a, x, y, w, h, c1, c2, period=2):
    for yy in range(y, y + h):
        for xx in range(x, x + w):
            put(a, xx, yy, c1 if (xx + yy) % period else c2)


def corrugated(a, x, y, w, h, pal, vertical=True, step=3):
    """Mái tôn: sóng tôn song song, sáng ở mép trên, tối ở mép dưới."""
    rect(a, x, y, w, h, pal[1])
    if vertical:
        for xx in range(x, x + w, step):
            vline(a, xx, y, y + h - 1, pal[2])
            vline(a, xx + 1, y, y + h - 1, pal[0])
    else:
        for yy in range(y, y + h, step):
            hline(a, x, x + w - 1, yy, pal[2])
            hline(a, x, x + w - 1, yy + 1, pal[0])
    hline(a, x, x + w - 1, y + h - 1, pal[3])


def tiles_roof(a, x, y, w, h, pal):
    """Mái ngói: hàng ngói so le."""
    rect(a, x, y, w, h, pal[1])
    for i, yy in enumerate(range(y, y + h, 4)):
        hline(a, x, x + w - 1, yy, pal[2])
        off = 0 if i % 2 == 0 else 3
        for xx in range(x + off, x + w, 6):
            vline(a, xx, yy, min(yy + 3, y + h - 1), pal[2])
            put(a, xx + 1, yy + 1, pal[0])
            put(a, xx + 2, yy + 1, pal[0])
    hline(a, x, x + w - 1, y + h - 1, pal[3])


def stripes(a, x, y, w, h, c1, c2, width=4):
    for xx in range(x, x + w):
        col = c1 if ((xx - x) // width) % 2 == 0 else c2
        vline(a, xx, y, y + h - 1, col)


def hue_shift(arr, deg, mask=None, sat_min=0.18, skip_skin=True):
    """Đổi màu (xoay hue) các pixel đủ bão hoà; bỏ qua da người. Dùng để đổi màu áo/hàng hoá cho đa dạng."""
    out = arr.copy()
    h, w = arr.shape[:2]
    for yy in range(h):
        for xx in range(w):
            if out[yy, xx, 3] == 0 or (mask is not None and not mask[yy, xx]):
                continue
            r, g, b = (out[yy, xx, :3] / 255.0)
            hh, ss, vv = colorsys.rgb_to_hsv(r, g, b)
            if ss < sat_min:
                continue
            if skip_skin and (hh < 0.12 or hh > 0.97) and ss < 0.72 and vv > 0.35:
                continue  # da người (cam nâu nhạt)
            r, g, b = colorsys.hsv_to_rgb((hh + deg / 360.0) % 1.0, ss, vv)
            out[yy, xx, :3] = (int(r * 255), int(g * 255), int(b * 255))
    return out


def shade(c, k):
    return (min(255, int(c[0] * k)), min(255, int(c[1] * k)), min(255, int(c[2] * k)), c[3])


