def text_width(text, font=FONT5x7, gap=1):
    return sum(len(font.get(ch, font[" "])[0]) + gap for ch in text) - gap


def draw_text(a, x, y, text, color, font=FONT5x7, gap=1, shadow=None):
    for ch in text:
        glyph = font.get(ch, font[" "])
        for gy, row in enumerate(glyph):
            for gx, bit in enumerate(row):
                if bit == "1":
                    if shadow is not None:
                        put(a, x + gx + 1, y + gy + 1, shadow)
                    put(a, x + gx, y + gy, color)
        x += len(glyph[0]) + gap
    return x


def sign_board(text, bg, fg, font=FONT5x7, pad=3, border=OUTLINE, shadow=None):
    w = text_width(text, font) + pad * 2 + 2
    h = len(font["A"]) + pad * 2 + 2
    a = canvas(w, h)
    rect(a, 0, 0, w, h, border)
    rect(a, 1, 1, w - 2, h - 2, bg)
    hline(a, 1, w - 2, 1, shade(bg, 1.15) if bg[0] < 220 else bg)
    draw_text(a, pad + 1, pad + 1, text, fg, font, shadow=shadow)
    return a
